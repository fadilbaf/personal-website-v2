/**
 * Universal LinkIcon renderer matching any icon identifier string (case-insensitive)
 */
export function LinkIcon({
  name,
  className,
}: {
  name?: string | null;
  className?: string;
}) {
  if (!name) return <Globe className={className} />;

  const key = name.trim().toLowerCase();

  const found = AVAILABLE_LINK_ICONS.find(
    (item) => item.name.toLowerCase() === key
  );

  if (found) {
    const IconComp = found.component;
    return <IconComp className={className} />;
  }

  // Fallback defaults
  switch (key) {
    case "github":
    case "git":
      return <GitHubIcon className={className} />;
    case "linkedin":
      return <LinkedInIcon className={className} />;
    case "instagram":
      return <InstagramIcon className={className} />;
    case "tiktok":
      return <TikTokIcon className={className} />;
    case "youtube":
      return <YouTubeIcon className={className} />;
    case "twitter":
    case "x":
      return <TwitterIcon className={className} />;
    case "whatsapp":
    case "wa":
      return <WhatsAppIcon className={className} />;
    case "threads":
      return <ThreadsIcon className={className} />;
    case "discord":
      return <DiscordIcon className={className} />;
    case "telegram":
      return <Send className={className} />;
    case "mail":
    case "email":
      return <Mail className={className} />;
    case "cv":
    case "resume":
    case "document":
      return <FileText className={className} />;
    default:
      return <Globe className={className} />;
  }
}
